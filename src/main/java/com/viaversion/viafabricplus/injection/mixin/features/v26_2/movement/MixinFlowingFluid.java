package com.viaversion.viafabricplus.injection.mixin.features.v26_2.movement;

import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import com.viaversion.viafabricplus.ViaFabricPlus;
import com.viaversion.viaversion.api.protocol.version.ProtocolVersion;
import net.minecraft.tags.TagKey;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.material.FlowingFluid;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

@Mixin(FlowingFluid.class)
public abstract class MixinFlowingFluid {

    @WrapOperation(method = "getFlow", at = @At(value = "INVOKE", target = "Lnet/minecraft/world/level/block/state/BlockState;is(Lnet/minecraft/tags/TagKey;)Z"))
    private boolean useBlocksMotion(BlockState instance, TagKey<Block> tag, Operation<Boolean> original) {
        // 26.2 used BlockState#blocksMotion, which unlike the tag, depends on the block state
        if (ViaFabricPlus.api().targetVersion().olderThanOrEqualTo(ProtocolVersion.v26_2)) {
            return !instance.is(Blocks.COBWEB) && !instance.is(Blocks.BAMBOO_SAPLING) && instance.isSolid();
        } else {
            return original.call(instance, tag);
        }
    }

}
